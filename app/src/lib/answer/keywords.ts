/**
 * 질문에 노동·인사 용어가 하나라도 들어 있는가.
 * 있으면 검색 결과가 빈약하더라도 '무관한 질문'으로 단정하지 않는다.
 */
export function looksLaborRelated(question: string): boolean {
  if (typeof question !== 'string') return false;
  const text = question.replace(/\s+/g, '');
  return LABOR_TERMS.some((term) => text.includes(term));
}
